namespace AnimStudio.Application.Tests.StoryAgent;

public class StoryBundleBuilderTests
{
    private static readonly byte[] Jpeg = [0xFF, 0xD8, 0xFF, 0xE0, 0, 16, 0x4A, 0x46, 0x49, 0x46];
    private static readonly byte[] Wav = Encoding.ASCII.GetBytes("RIFF....WAVEfmt ");

    private static List<StoryBundleScene> SceneMedia(StoryScript script, bool withAudio = true) =>
        [.. script.Scenes.Select(s => new StoryBundleScene(
            s.Number, Jpeg, "image/jpeg", "Generated by the app's image engine",
            withAudio ? Wav : null, withAudio ? "Narration in a stock voice" : null,
            withAudio ? 8.0 + s.Number : s.EstimatedSeconds,
            withAudio ? [new StoryPause { Start = 0, End = 0.4 }] : []))];

    private static StoryBundleOutput Build(bool withAudio = true, bool withMusic = true, StoryFormat format = StoryFormat.Wide)
    {
        var script = StorySamples.Script();
        var brief = StorySamples.Brief();
        brief.Format = format;
        var music = withMusic
            ? new StoryBundleMusic([1, 2, 3], "\"kRaga3\" by KraftiM", "https://www.jamendo.com/track/118260", LicenseClass.AttributionOnly)
            : null;
        return StoryBundleBuilder.Build(script, brief, new StoryBuildOptions { MusicVolume = 0.2 }, "Story: दीपावली", SceneMedia(script, withAudio), music);
    }

    [Fact]
    public void The_bundle_the_builder_makes_is_valid_for_the_importer_that_reads_it()
    {
        var output = Build();

        var data = WorkbookReader.Read(output.Bundle.Workbook);

        Assert.Empty(data.Errors);
        Assert.Equal("Story: दीपावली", data.Project!.Text("Name"));
        Assert.Equal(1920, data.Project.Integer("Width"));
        Assert.Equal(1080, data.Project.Integer("Height"));
        Assert.Equal(30, data.Project.Integer("FrameRate"));
        Assert.Equal(0.2, data.Project.Number("BackgroundMusicVolume"));
        Assert.Equal("media/music.mp3", data.Project.Text("BackgroundMusic"));
        Assert.Equal(6, data.Scenes.Count);
        Assert.Equal(output.CaptionCount, data.Dialogue.Count);
        Assert.Equal(6 + 6 + 1, data.Assets.Count);
    }

    [Fact]
    public void A_vertical_video_gets_a_vertical_canvas()
    {
        var data = WorkbookReader.Read(Build(format: StoryFormat.Vertical).Bundle.Workbook);

        Assert.Equal(1080, data.Project!.Integer("Width"));
        Assert.Equal(1920, data.Project.Integer("Height"));
    }

    [Fact]
    public void Every_cell_that_names_a_file_names_one_that_is_in_the_bundle()
    {
        var output = Build();
        var data = WorkbookReader.Read(output.Bundle.Workbook);

        foreach (var scene in data.Scenes)
        {
            Assert.NotNull(output.Bundle.Resolve(scene.Text("Background")));
            Assert.NotNull(output.Bundle.Resolve(scene.Text("Audio")));
        }
        Assert.NotNull(output.Bundle.Resolve(data.Project!.Text("BackgroundMusic")));
        Assert.All(output.Bundle.Media.Values, m => Assert.NotEmpty(m.Content));
        Assert.Equal(AssetKind.Audio, output.Bundle.Resolve("media/music.mp3")!.Kind);
        Assert.Equal(AssetKind.Image, output.Bundle.Resolve("media/img-s01.jpg")!.Kind);
    }

    [Fact]
    public void Scenes_alternate_their_motion_fade_into_each_other_and_the_last_ends_cleanly()
    {
        var scenes = WorkbookReader.Read(Build().Bundle.Workbook).Scenes;

        Assert.Equal(["ZoomIn", "PanRight", "ZoomOut", "PanLeft", "ZoomIn", "PanRight"], scenes.Select(s => s.Text("Effect")));
        Assert.All(scenes.Take(5), s => { Assert.Equal("Fade", s.Text("Transition")); Assert.Equal(0.45, s.Number("TransitionSeconds")); });
        Assert.Equal("None", scenes[^1].Text("Transition"));
        Assert.Equal(0.0, scenes[^1].Number("TransitionSeconds"));
    }

    [Fact]
    public void Scene_starts_take_the_overlap_of_the_fades_out_like_the_renderer_does()
    {
        var output = Build();

        // Scene n lasts 8+n seconds = 30fps frames; each of the first five fades into the next for 14 frames.
        Assert.Equal(0.0, output.SceneStarts[0]);
        Assert.Equal(Math.Round((9 * 30 - 14) / 30.0, 2), output.SceneStarts[1]);
        Assert.Equal(Math.Round((9 * 30 + 10 * 30 - 28) / 30.0, 2), output.SceneStarts[2]);
        var totalFrames = Enumerable.Range(1, 6).Sum(n => (8 + n) * 30) - 5 * 14;
        Assert.Equal(Math.Round(totalFrames / 30.0, 2), output.TotalSeconds);
        Assert.True(output.SceneStarts.Zip(output.SceneStarts.Skip(1)).All(p => p.Second > p.First));
    }

    [Fact]
    public void Captions_cover_every_scene_in_order_and_stay_inside_their_scene()
    {
        var data = WorkbookReader.Read(Build().Bundle.Workbook);

        foreach (var scene in data.Scenes)
        {
            var number = scene.Integer("SceneNumber");
            var seconds = scene.Number("DurationSeconds")!.Value;
            var lines = data.Dialogue.Where(d => d.Integer("SceneNumber") == number).OrderBy(d => d.Integer("Order")).ToList();

            Assert.NotEmpty(lines);
            double previousEnd = 0;
            foreach (var line in lines)
            {
                var start = line.Number("StartSeconds")!.Value;
                var end = line.Number("EndSeconds")!.Value;
                Assert.InRange(start, previousEnd - 0.011, seconds);
                Assert.InRange(end, start, seconds + 0.001);
                previousEnd = end;
            }
        }
    }

    [Fact]
    public void A_scene_without_audio_is_timed_by_its_estimate_and_its_captions_are_spread_across_it()
    {
        var data = WorkbookReader.Read(Build(withAudio: false, withMusic: false).Bundle.Workbook);

        Assert.All(data.Scenes, s => Assert.Null(s.Text("Audio")));
        Assert.Null(data.Project!.Text("BackgroundMusic"));
        Assert.DoesNotContain(data.Assets, a => a.Text("Kind") == "Audio");
        Assert.All(data.Scenes, s => Assert.True(s.Number("DurationSeconds") >= StoryPacing.MinSceneSeconds));
    }

    [Fact]
    public void Licences_and_credits_are_recorded_with_the_files()
    {
        var data = WorkbookReader.Read(Build().Bundle.Workbook);

        var music = data.Assets.Single(a => a.Text("Name") == "music");
        Assert.Equal("AttributionOnly", music.Text("License"));
        Assert.Contains("kRaga3", music.Text("Attribution"));
        Assert.Equal("https://www.jamendo.com/track/118260", music.Text("SourceUrl"));
        Assert.Contains("image engine", data.Assets.First(a => a.Text("Name") == "img-s01").Text("Attribution"));
    }

    [Fact]
    public void A_project_without_a_picture_for_every_scene_is_refused_before_anything_is_written()
    {
        var script = StorySamples.Script();

        Assert.Throws<InvalidOperationException>(() => StoryBundleBuilder.Build(
            script, StorySamples.Brief(), new StoryBuildOptions(), "x", SceneMedia(script).Take(3).ToList(), null));
    }
}

public class StoryKitBuilderTests
{
    private static StoryKitFacts Facts(StoryScript script, bool music = true, bool ai = true, StoryNarrationMode narration = StoryNarrationMode.MyVoice)
    {
        var starts = new List<double>();
        double at = 0;
        foreach (var scene in script.Scenes)
        {
            starts.Add(Math.Round(at, 2));
            at += 14.0;
        }
        return new StoryKitFacts(starts, at, ai, narration,
            music ? new StoryMusicPick
            {
                Title = "kRaga3", Artist = "KraftiM", PageUrl = "https://www.jamendo.com/track/118260",
                LicenseCode = "CC BY 3.0", LicenseUrl = "https://creativecommons.org/licenses/by/3.0/", Attribution = "x"
            } : null,
            new ChannelBranding
            {
                ChannelName = "OMKR", ChannelUrl = "https://youtube.com/@omkr-shiv", StudioUrl = "https://studio.keshavsingh.in/",
                CreatorUrl = "https://keshavsingh.in/", EngineName = "AnimStudio", Hashtags = ["OMKR", "AnimStudio", "KeshavSingh"],
                Tags = ["omkr", "keshav singh"]
            });
    }

    private static StoryPublishKit Kit(StoryScript? script = null, StoryKitFacts? facts = null, string language = "hi")
    {
        script ??= StorySamples.Script();
        return StoryKitBuilder.Build(script, StorySamples.Brief(language), StorySamples.Research(), facts ?? Facts(script));
    }

    [Fact]
    public void Everything_in_the_kit_fits_youtubes_own_limits()
    {
        var kit = Kit();

        Assert.NotEmpty(kit.TitleOptions);
        Assert.All(kit.TitleOptions, t => Assert.InRange(t.Length, 1, YouTubePublishValidator.MaxTitleLength));
        Assert.True(Encoding.UTF8.GetByteCount(kit.Description) <= YouTubePublishValidator.MaxDescriptionBytes);
        Assert.Equal(Encoding.UTF8.GetByteCount(kit.Description), kit.DescriptionBytes);
        Assert.True(YouTubePublishValidator.TagsLength(kit.Tags) <= YouTubePublishValidator.MaxTagsLength);
        Assert.Equal(YouTubePublishValidator.TagsLength(kit.Tags), kit.TagsLength);
        Assert.InRange(kit.Hashtags.Count, 1, 5);
        Assert.DoesNotContain("<", kit.Description);
        Assert.DoesNotContain(kit.Tags, t => t.Contains(',') || t.Contains('#'));
    }

    [Fact]
    public void A_very_long_title_is_cut_at_a_word_to_fit()
    {
        var script = StorySamples.Script();
        script.Title = string.Join(' ', Enumerable.Repeat("दीपावली की महिमा", 12));
        script.TitleEnglish = string.Join(' ', Enumerable.Repeat("Glory of Diwali", 12));

        Assert.All(Kit(script).TitleOptions, t => Assert.True(t.Length <= 100, t));
    }

    [Fact]
    public void Chapters_start_at_zero_number_at_least_three_and_each_last_ten_seconds()
    {
        var kit = Kit();

        Assert.True(kit.Chapters.Count >= YouTubeChapterBuilder.MinChapters);
        Assert.Equal("0:00", kit.Chapters[0].Stamp);
        Assert.Equal(0, kit.Chapters[0].StartSeconds);
        for (var i = 1; i < kit.Chapters.Count; i++)
            Assert.True(kit.Chapters[i].StartSeconds - kit.Chapters[i - 1].StartSeconds >= YouTubeChapterBuilder.MinChapterSeconds);
        Assert.Contains("⏱️ Chapters", kit.Description);
        Assert.Contains($"{kit.Chapters[1].Stamp} {kit.Chapters[1].Title}", kit.Description);
    }

    [Fact]
    public void A_video_too_short_for_chapters_gets_none()
    {
        var script = StorySamples.Script();
        var facts = Facts(script) with { TotalSeconds = 40 };

        var kit = Kit(script, facts);

        Assert.Empty(kit.Chapters);
        Assert.DoesNotContain("Chapters", kit.Description);
    }

    [Fact]
    public void Only_citations_that_exist_are_printed_and_the_rest_are_reported_in_the_checklist()
    {
        var kit = Kit();

        Assert.Contains("• Bhagavata Purana 8.8", kit.Description);
        Assert.Contains("• Bhagavata Purana 10.59", kit.Description);
        Assert.DoesNotContain("13.2", kit.Description);
        Assert.Contains(kit.Checklist, c => c.Contains("citations in the script do not exist", StringComparison.Ordinal));
    }

    [Fact]
    public void The_music_credit_and_the_ai_disclosure_are_there_when_they_apply()
    {
        var kit = Kit();

        Assert.Contains("🎵 Music used:", kit.Description);
        Assert.Contains("\"kRaga3\" - KraftiM", kit.Description);
        Assert.Contains("https://creativecommons.org/licenses/by/3.0/", kit.Description);
        Assert.DoesNotContain("(https://", kit.Description);
        Assert.Contains("चित्र: AI से बने भक्ति-चित्र", kit.Description);
        Assert.Contains("स्वर: निर्माता की अपनी आवाज़ पर आधारित AI वॉइस", kit.Description);
        Assert.Contains(kit.Checklist, c => c.StartsWith("Set \"AI use\" to Yes", StringComparison.Ordinal));
        Assert.Contains(kit.Checklist, c => c.Contains("music credit", StringComparison.Ordinal));
    }

    [Fact]
    public void A_video_with_no_ai_no_voice_and_no_music_claims_none_of_them()
    {
        var script = StorySamples.Script();
        var kit = Kit(script, Facts(script, music: false, ai: false, narration: StoryNarrationMode.None));

        Assert.DoesNotContain("🎵", kit.Description);
        Assert.DoesNotContain("AI", kit.Description.Replace("AnimStudio", string.Empty));
        Assert.DoesNotContain(kit.Checklist, c => c.Contains("AI use", StringComparison.Ordinal));
    }

    [Fact]
    public void The_brand_block_hashtags_and_tags_come_from_the_channels_branding()
    {
        var kit = Kit();

        Assert.Contains("Animation Engine: AnimStudio - https://studio.keshavsingh.in/", kit.Description);
        Assert.Contains("Creator: https://keshavsingh.in/ | Presented by: OMKR", kit.Description);
        Assert.Contains("🔔 Subscribe to OMKR: https://youtube.com/@omkr-shiv", kit.Description);
        Assert.EndsWith(string.Join(' ', kit.Hashtags), kit.Description);
        Assert.Contains("#OMKR", kit.Hashtags);
        Assert.Contains("omkr", kit.Tags);
        Assert.Contains("keshav singh", kit.Tags);
    }

    [Fact]
    public void Hashtags_follow_the_topic_in_hindi_and_english()
    {
        var kit = Kit();

        Assert.Contains(kit.Hashtags, h => h is "#दिवाली" or "#दीपावली");
        Assert.Contains("#Diwali", kit.Hashtags);
        Assert.All(kit.Hashtags, h => Assert.Matches(@"^#[\p{L}\p{M}\p{N}_]+$", h));
    }

    [Fact]
    public void The_comments_invite_a_jaikara_and_a_reply_with_a_chapter_number()
    {
        var kit = Kit();

        Assert.Contains("जय श्री राम", kit.PinnedComment);
        Assert.Contains("1️⃣", kit.EngagementComment);
        Assert.DoesNotContain("http", kit.PinnedComment);
    }

    [Fact]
    public void An_english_kit_is_written_in_english()
    {
        var kit = Kit(language: "en");

        Assert.Contains("Which part of this video", kit.EngagementComment);
        Assert.Contains("📖 Sources", kit.Description);
        Assert.Contains("Jai Shri Ram", kit.PinnedComment);
        Assert.Contains(kit.TitleOptions, t => t.Contains("Story, Sources and Meaning", StringComparison.Ordinal));
    }

    [Fact]
    public void A_description_that_would_overflow_sheds_optional_parts_before_required_ones()
    {
        var script = StorySamples.Script();
        foreach (var scene in script.Scenes)
        {
            scene.Sources.Clear();
            for (var i = 1; i <= 40; i++)
                scene.Sources.Add(new StorySourceRef
                {
                    TextId = "bhagavata-purana", TextName = "Bhagavata Purana", Ref = $"10.{i}", Check = CitationStatus.Verified,
                    Note = new string('न', 200)
                });
        }

        var kit = Kit(script);

        Assert.True(Encoding.UTF8.GetByteCount(kit.Description) <= YouTubePublishValidator.MaxDescriptionBytes);
        Assert.Contains("🎵 Music used:", kit.Description);
        Assert.Contains("🎬", kit.Description);
        Assert.EndsWith(string.Join(' ', kit.Hashtags), kit.Description);
    }
}
