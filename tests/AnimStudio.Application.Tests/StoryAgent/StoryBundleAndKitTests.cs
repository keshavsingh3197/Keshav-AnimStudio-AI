public class StoryKitBuilderTests
{
    private static StoryKitFacts Facts(StoryScript script, bool music = true, bool ai = true, StoryNarrationMode narration = StoryNarrationMode.MyVoice)
    {
        var starts = new List<double>();
        double at = 0;
        foreach (var scene in script.Scenes)
        {
            starts.Add(Math.Round(at, 2));
            at += 14.0;
        }
        return new StoryKitFacts(starts, at, ai, narration,
            music ? new StoryMusicPick
            {
                Title = "kRaga3", Artist = "KraftiM", PageUrl = "https://www.jamendo.com/track/118260",
                LicenseCode = "CC BY 3.0", LicenseUrl = "https://creativecommons.org/licenses/by/3.0/", Attribution = "x"
            } : null,
            new ChannelBranding
            {
                ChannelName = "Omkar Shiv Bhakti", ChannelUrl = "https://youtube.com/@OmkarShivBhakti", StudioUrl = "https://studio.keshavsingh.in/",
                CreatorUrl = "https://keshavsingh.in/", EngineName = "AnimStudio", Hashtags = ["OmkarShivBhakti", "AnimStudio", "KeshavSingh"],
                Tags = ["omkar shiv bhakti", "keshav singh"]
            });
    }

    private static StoryPublishKit Kit(StoryScript? script = null, StoryKitFacts? facts = null, string language = "hi")
    {
        script ??= StorySamples.Script();
        return StoryKitBuilder.Build(script, StorySamples.Brief(language), StorySamples.Research(), facts ?? Facts(script));
    }

    [Fact]
    public void Everything_in_the_kit_fits_youtubes_own_limits()
    {
        var kit = Kit();

        Assert.NotEmpty(kit.TitleOptions);
        Assert.All(kit.TitleOptions, t => Assert.InRange(t.Length, 1, YouTubePublishValidator.MaxTitleLength));
        Assert.True(Encoding.UTF8.GetByteCount(kit.Description) <= YouTubePublishValidator.MaxDescriptionBytes);
        Assert.Equal(Encoding.UTF8.GetByteCount(kit.Description), kit.DescriptionBytes);
        Assert.True(YouTubePublishValidator.TagsLength(kit.Tags) <= YouTubePublishValidator.MaxTagsLength);
        Assert.Equal(YouTubePublishValidator.TagsLength(kit.Tags), kit.TagsLength);
        Assert.InRange(kit.Hashtags.Count, 1, 5);
        Assert.DoesNotContain("<", kit.Description);
        Assert.DoesNotContain(kit.Tags, t => t.Contains(',') || t.Contains('#'));
    }

    [Fact]
    public void A_very_long_title_is_cut_at_a_word_to_fit()
    {
        var script = StorySamples.Script();
        script.Title = string.Join(' ', Enumerable.Repeat("दीपावली की महिमा", 12));
        script.TitleEnglish = string.Join(' ', Enumerable.Repeat("Glory of Diwali", 12));

        Assert.All(Kit(script).TitleOptions, t => Assert.True(t.Length <= 100, t));
    }

    [Fact]
    public void Chapters_start_at_zero_number_at_least_three_and_each_last_ten_seconds()
    {
        var kit = Kit();

        Assert.True(kit.Chapters.Count >= YouTubeChapterBuilder.MinChapters);
        Assert.Equal("0:00", kit.Chapters[0].Stamp);
        Assert.Equal(0, kit.Chapters[0].StartSeconds);
        for (var i = 1; i < kit.Chapters.Count; i++)
            Assert.True(kit.Chapters[i].StartSeconds - kit.Chapters[i - 1].StartSeconds >= YouTubeChapterBuilder.MinChapterSeconds);
        Assert.Contains("⏱️ Chapters", kit.Description);
        Assert.Contains($"{kit.Chapters[1].Stamp} {kit.Chapters[1].Title}", kit.Description);
    }

    [Fact]
    public void A_video_too_short_for_chapters_gets_none()
    {
        var script = StorySamples.Script();
        var facts = Facts(script) with { TotalSeconds = 40 };

        var kit = Kit(script, facts);

        Assert.Empty(kit.Chapters);
        Assert.DoesNotContain("Chapters", kit.Description);
    }

    [Fact]
    public void Only_citations_that_exist_are_printed_and_the_rest_are_reported_in_the_checklist()
    {
        var kit = Kit();

        Assert.Contains("• Bhagavata Purana 8.8", kit.Description);
        Assert.Contains("• Bhagavata Purana 10.59", kit.Description);
        Assert.DoesNotContain("13.2", kit.Description);
        Assert.Contains(kit.Checklist, c => c.Contains("citations in the script do not exist", StringComparison.Ordinal));
    }

    [Fact]
    public void The_music_credit_and_the_ai_disclosure_are_there_when_they_apply()
    {
        var kit = Kit();

        Assert.Contains("🎵 Music used:", kit.Description);
        Assert.Contains("\"kRaga3\" - KraftiM", kit.Description);
        Assert.Contains("https://creativecommons.org/licenses/by/3.0/", kit.Description);
        Assert.DoesNotContain("(https://", kit.Description);
        Assert.Contains("चित्र: AI से बने भक्ति-चित्र", kit.Description);
        Assert.Contains("स्वर: निर्माता की अपनी आवाज़ पर आधारित AI वॉइस", kit.Description);
        Assert.Contains(kit.Checklist, c => c.StartsWith("Set \"AI use\" to Yes", StringComparison.Ordinal));
        Assert.Contains(kit.Checklist, c => c.Contains("music credit", StringComparison.Ordinal));
    }

    [Fact]
    public void A_video_with_no_ai_no_voice_and_no_music_claims_none_of_them()
    {
        var script = StorySamples.Script();
        var kit = Kit(script, Facts(script, music: false, ai: false, narration: StoryNarrationMode.None));

        Assert.DoesNotContain("🎵", kit.Description);
        Assert.DoesNotContain("AI", kit.Description.Replace("AnimStudio", string.Empty));
        Assert.DoesNotContain(kit.Checklist, c => c.Contains("AI use", StringComparison.Ordinal));
    }

    [Fact]
    public void The_brand_block_hashtags_and_tags_come_from_the_channels_branding()
    {
        var kit = Kit();

        Assert.Contains("Animation Engine: AnimStudio - https://studio.keshavsingh.in/", kit.Description);
        Assert.Contains("Creator: https://keshavsingh.in/ | Presented by: Omkar Shiv Bhakti", kit.Description);
        Assert.Contains("🔔 Subscribe to Omkar Shiv Bhakti: https://youtube.com/@OmkarShivBhakti", kit.Description);
        Assert.EndsWith(string.Join(' ', kit.Hashtags), kit.Description);
        Assert.Contains("#OmkarShivBhakti", kit.Hashtags);
        Assert.Contains("omkar shiv bhakti", kit.Tags);
