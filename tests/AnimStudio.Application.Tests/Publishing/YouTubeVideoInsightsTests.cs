public sealed class YouTubeMusicDetectorTests
{
    [Fact]
    public void Credit_lines_make_one_song_with_its_people()
    {
        var songs = YouTubeMusicDetector.FromDescription("""
            A road trip through the hills.

            🎵 Song: Kesariya
            Singer: Arijit Singh
            Music: Pritam | Lyrics: Amitabh Bhattacharya
            Label: Sony Music India
            """);

        var song = Assert.Single(songs);
        Assert.Equal("Kesariya", song.Title);
        Assert.Equal("Arijit Singh", song.Artist);
        Assert.Equal(YouTubeMusicDetector.SourceDescription, song.Source);
        Assert.Equal("Music: Pritam · Lyrics: Amitabh Bhattacharya · Label: Sony Music India", song.Credits);
    }

    [Fact]
    public void Each_song_line_starts_a_new_song()
    {
        var songs = YouTubeMusicDetector.FromDescription("""
            Track: Morning Light
            Artist: Lo Fi Lab
            Track: Night Drive
            Artist: Synth Club
            """);

        Assert.Equal(2, songs.Count);
        Assert.Equal(("Morning Light", "Lo Fi Lab"), (songs[0].Title, songs[0].Artist));
        Assert.Equal(("Night Drive", "Synth Club"), (songs[1].Title, songs[1].Artist));
    }

    [Fact]
    public void Music_note_lines_are_read_as_title_and_artist()
    {
        var songs = YouTubeMusicDetector.FromDescription("♪ Blinding Lights - The Weeknd\n♫ Levitating by Dua Lipa");

        Assert.Equal(2, songs.Count);
        Assert.Equal(("Blinding Lights", "The Weeknd"), (songs[0].Title, songs[0].Artist));
        Assert.Equal(("Levitating", "Dua Lipa"), (songs[1].Title, songs[1].Artist));
    }

    [Fact]
    public void Auto_generated_art_track_description_is_read()
    {
        var songs = YouTubeMusicDetector.FromDescription("""
            Provided to YouTube by Saregama India Ltd

            Lag Ja Gale · Lata Mangeshkar · Madan Mohan

            Woh Kaun Thi

            ℗ 1964 Saregama India Ltd

            Released on: 1964-01-01

            Composer: Madan Mohan

            Auto-generated by YouTube.
            """);

        var song = Assert.Single(songs);
        Assert.Equal("Lag Ja Gale", song.Title);
        Assert.Equal("Lata Mangeshkar, Madan Mohan", song.Artist);
        Assert.Equal("Woh Kaun Thi", song.Album);
        Assert.Contains("Label: Saregama India Ltd", song.Credits);
        Assert.Contains("Music: Madan Mohan", song.Credits);
    }

    [Fact]
    public void Hindi_credit_labels_are_read()
    {
        var songs = YouTubeMusicDetector.FromDescription("गीत: ॐ नमः शिवाय\nगायक: राहुल\nसंगीत: अमित");

        var song = Assert.Single(songs);
        Assert.Equal("ॐ नमः शिवाय", song.Title);
        Assert.Equal("राहुल", song.Artist);
        Assert.Equal("Music: अमित", song.Credits);
    }

    [Fact]
    public void Credits_without_a_song_name_are_kept_as_music_credits()
    {
        var song = Assert.Single(YouTubeMusicDetector.FromDescription("Music: YouTube Audio Library"));

        Assert.Equal(YouTubeMusicDetector.UntitledCredits, song.Title);
        Assert.Equal("Music: YouTube Audio Library", song.Credits);
    }

    [Fact]
    public void Ordinary_lines_and_empty_labels_are_not_songs()
    {
        var songs = YouTubeMusicDetector.FromDescription("""
            Track your progress: https://example.com
            Lyrics:
            In this video we bake bread.
            Watch - the full series
            """);

        Assert.Empty(songs);
    }

    [Fact]
    public void Values_lose_angle_brackets_and_are_capped()
    {
        var song = Assert.Single(YouTubeMusicDetector.FromDescription("Song: <b>" + new string('a', 200)));

        Assert.DoesNotContain('<', song.Title);
        Assert.True(song.Title.Length <= 100);
    }

    [Fact]
    public void Music_section_cards_are_read_from_innertube_next()
    {
        using var doc = JsonDocument.Parse("""
            {"engagementPanels":[{"engagementPanelSectionListRenderer":{"content":{"structuredDescriptionContentRenderer":{"items":[
              {"horizontalCardListRenderer":{"header":{"richListHeaderRenderer":{"title":{"simpleText":"Places"}}},
                "cards":[{"videoAttributeViewModel":{"title":"Not A Song","subtitle":"Somewhere"}}]}},
              {"horizontalCardListRenderer":{"header":{"richListHeaderRenderer":{"title":{"runs":[{"text":"Music"}]}}},
                "cards":[
                  {"videoAttributeViewModel":{"title":"Shape of You","subtitle":"Ed Sheeran","secondarySubtitle":{"content":"÷ (Deluxe)"}}},
                  {"videoAttributeViewModel":{"title":{"content":"Perfect"},"subtitle":{"content":"Ed Sheeran"}}}
                ]}}
            ]}}}}]}
            """);

        var songs = YouTubeMusicDetector.FromInnertubeNext(doc.RootElement);

        Assert.Equal(2, songs.Count);
        Assert.Equal(new YouTubeDetectedSong("Shape of You", "Ed Sheeran", "÷ (Deluxe)", YouTubeMusicDetector.SourceMusicCard), songs[0]);
        Assert.Equal(("Perfect", "Ed Sheeran"), (songs[1].Title, songs[1].Artist));
    }

    [Fact]
    public void Older_music_section_rows_are_read_from_innertube_next()
    {
        using var doc = JsonDocument.Parse("""
            {"contents":{"x":[{"videoDescriptionMusicSectionRenderer":{"sectionTitle":{"simpleText":"Music"},"carouselLockups":[
              {"carouselLockupRenderer":{"infoRows":[
                {"infoRowRenderer":{"title":{"simpleText":"SONG"},"defaultMetadata":{"simpleText":"Tum Hi Ho"}}},
                {"infoRowRenderer":{"title":{"simpleText":"ARTIST"},"defaultMetadata":{"runs":[{"text":"Arijit "},{"text":"Singh"}]}}},
                {"infoRowRenderer":{"title":{"simpleText":"ALBUM"},"expandedMetadata":{"simpleText":"Aashiqui 2"}}},
                {"infoRowRenderer":{"title":{"simpleText":"LICENSES"},"defaultMetadata":{"simpleText":"T-Series"}}}
              ]}}
            ]}}]}}
            """);

        var song = Assert.Single(YouTubeMusicDetector.FromInnertubeNext(doc.RootElement));

        Assert.Equal(new YouTubeDetectedSong("Tum Hi Ho", "Arijit Singh", "Aashiqui 2", YouTubeMusicDetector.SourceMusicCard), song);
    }

    [Fact]
    public void Unexpected_innertube_shapes_find_nothing_and_do_not_throw()
    {
        using var doc = JsonDocument.Parse("""
            {"horizontalCardListRenderer":"oops","videoDescriptionMusicSectionRenderer":{"carouselLockups":[1,null,{"carouselLockupRenderer":{"infoRows":"x"}}]},
             "a":[[[[{"horizontalCardListRenderer":{"header":{"richListHeaderRenderer":{"title":{"simpleText":"Music"}}},"cards":[{"videoAttributeViewModel":{"title":42}}]}}]]]]}
            """);

        Assert.Empty(YouTubeMusicDetector.FromInnertubeNext(doc.RootElement));
    }

    [Fact]
    public void Merge_keeps_the_card_and_drops_the_same_song_from_the_description()
    {
        var card = new YouTubeDetectedSong("Kesariya", "Arijit Singh", null, YouTubeMusicDetector.SourceMusicCard);
        var described = new YouTubeDetectedSong("kesariya!", "Arijit", null, YouTubeMusicDetector.SourceDescription);
        var other = new YouTubeDetectedSong("Raataan Lambiyan", null, null, YouTubeMusicDetector.SourceDescription);

        var merged = YouTubeMusicDetector.Merge([card], [described, other]);

        Assert.Equal([card, other], merged);
    }
}

public sealed class YouTubeChapterBuilderTests
{
    private static List<YouTubeCaptionSegment> EverySeconds(int count, double step, string prefix = "Line") =>
        [.. Enumerable.Range(0, count).Select(i => new YouTubeCaptionSegment(i * step, $"{prefix} number {i} about the topic"))];

    [Fact]
    public void Chapters_start_at_zero_are_ordered_and_at_least_ten_seconds_apart()
    {
        var chapters = YouTubeChapterBuilder.FromSegments(EverySeconds(120, 5), 600);

        Assert.True(chapters.Count >= YouTubeChapterBuilder.MinChapters);
        Assert.Equal(0, chapters[0].StartSeconds);
        Assert.Equal("0:00", chapters[0].Stamp);
        for (var i = 1; i < chapters.Count; i++)
            Assert.True(chapters[i].StartSeconds - chapters[i - 1].StartSeconds >= YouTubeChapterBuilder.MinChapterSeconds);
        Assert.True(chapters[^1].StartSeconds <= 600 - YouTubeChapterBuilder.MinChapterSeconds);
    }

    [Fact]
    public void A_short_video_gets_no_chapters()
    {
        Assert.Empty(YouTubeChapterBuilder.FromSegments(EverySeconds(20, 2), 45));
    }

    [Fact]
    public void Too_few_usable_lines_give_no_chapters()
    {
        var segments = new List<YouTubeCaptionSegment>
        {
            new(0, "[Music]"), new(30, "♪ ♪"), new(60, "Hello there everyone"), new(90, "[Applause]"),
        };

        Assert.Empty(YouTubeChapterBuilder.FromSegments(segments, 300));
    }

    [Fact]
    public void Titles_are_cleaned_and_trimmed()
    {
        var segments = new List<YouTubeCaptionSegment>
        {
            new(0, "[Music] welcome to <b>the</b> show"),
            new(70, "now we talk about something that goes on and on far beyond any reasonable chapter title length"),
            new(140, "and finally the wrap up of everything"),
        };

        var chapters = YouTubeChapterBuilder.FromSegments(segments, 200);

        Assert.Equal(3, chapters.Count);
        Assert.Equal("Welcome to b the /b show", chapters[0].Title);
        Assert.True(chapters[1].Title.Length <= YouTubeChapterBuilder.MaxTitleChars + 1);
        Assert.EndsWith("…", chapters[1].Title);
        Assert.Equal("1:10", chapters[1].Stamp);
    }

    [Fact]
    public void Long_videos_use_hour_stamps_and_never_pass_the_cap()
    {
        var chapters = YouTubeChapterBuilder.FromSegments(EverySeconds(800, 6), 4800);

        Assert.True(chapters.Count <= YouTubeChapterBuilder.MaxChapters);
        Assert.Contains(chapters, c => c.Stamp.Count(ch => ch == ':') == 2);
    }

    [Fact]
    public void Timestamped_transcript_parses_back_into_segments()
    {
        var segments = YouTubeChapterBuilder.ParseTimestamped("[00:00] intro\n[01:05] middle\nno stamp\n[1:02:03] late");

        Assert.Equal([0d, 65d, 3723d], segments.Select(s => s.StartSeconds));
        Assert.Equal("middle", segments[1].Text);
    }

    [Fact]
    public void Description_block_and_detection_agree()
    {
        var chapters = new[] { new YouTubeChapter(0, "Intro"), new YouTubeChapter(30, "Middle"), new YouTubeChapter(75, "End") };

        var block = YouTubeChapterBuilder.ToDescriptionBlock(chapters);

        Assert.Contains("0:00 Intro\n0:30 Middle\n1:15 End", block);
        Assert.True(YouTubeChapterBuilder.HasChapters("Some text\n" + block));
        Assert.False(YouTubeChapterBuilder.HasChapters("Released 10:00 am"));
    }
}

public sealed class YouTubeVideoInsightsTests
{
    private static readonly YouTubeSeoExtras Extras = new(
        [new YouTubeDetectedSong("Kesariya", "Arijit Singh", null, YouTubeMusicDetector.SourceMusicCard)],
        [new YouTubeChapter(0, "Intro"), new YouTubeChapter(40, "The climb"), new YouTubeChapter(95, "Summit view")]);

    [Fact]
    public void Chapters_and_credits_are_added_once()
    {
        var once = YouTubeVideoInsights.AddChaptersAndCredits("A day in the hills.", Extras);
        var twice = YouTubeVideoInsights.AddChaptersAndCredits(once, Extras);

        Assert.Contains("0:00 Intro", once);
        Assert.Contains("🎵 Music used:\n• Kesariya - Arijit Singh", once);
        Assert.Equal(once, twice);
    }

    [Fact]
    public void Nothing_is_added_past_the_description_limit()
    {
        var full = new string('a', YouTubePublishValidator.MaxDescriptionBytes - 10);

        Assert.Equal(full, YouTubeVideoInsights.AddChaptersAndCredits(full, Extras));
    }

    [Fact]
    public void Prompt_lines_name_the_music_and_the_chapter_times()
    {
        var lines = YouTubeVideoInsights.PromptLines(Extras);

        Assert.Contains("Kesariya by Arijit Singh", lines);
        Assert.Contains("0:40 The climb", lines);
    }
}

public sealed class YouTubeFreeSeoEngineTests
{
    private const string Style = "a YouTube video - include topic hashtags in the description";

    [Fact]
    public void Non_devotional_content_gets_plain_topic_led_details()
    {
        var summary = "Channel: Bake Lab\nCurrent title: Sourdough bread for beginners\nCurrent tags: sourdough, baking, bread recipe";
        var transcript = "[00:00] today we bake sourdough bread\n[00:20] the starter needs flour and water\n[01:10] shape the sourdough loaf";

        var s = YouTubeFreeSeoEngine.Generate(summary, Style, "auto", "en", null, transcript);

        Assert.StartsWith("Sourdough bread for beginners", s.Title);
        Assert.DoesNotContain("OMKR", s.Description);
        Assert.DoesNotContain("Mahadev", s.Description);
        Assert.DoesNotContain("AnimStudio", s.Description);
        Assert.Contains("sourdough", s.Tags);
        Assert.Contains("#Sourdough", s.Description);
    }

    [Fact]
    public void Words_that_merely_contain_ram_are_not_devotional()
    {
        var s = YouTubeFreeSeoEngine.Generate("Current title: Program your Arduino in 10 minutes", Style, "auto", "en", null, null);

        Assert.DoesNotContain("Mahadev", s.Description);
        Assert.DoesNotContain("omkr", s.Tags);
    }

    [Fact]
    public void The_omkr_tone_keeps_the_devotional_template()
    {
        var s = YouTubeFreeSeoEngine.Generate("Current title: Shiv Tandav", Style, "devotional-omkr", "hi", null, null);

        Assert.Contains("OMKR", s.Description);
        Assert.Contains("omkr", s.Tags);
    }

    [Fact]
    public void Devotional_chapters_are_real_or_absent()
    {
        var without = YouTubeFreeSeoEngine.Generate("Current title: Shiv Tandav", Style, "devotional-omkr", "hi", null, null);
        Assert.All(without.DescriptionOptions, d => Assert.DoesNotContain("0:10", d));

        var extras = new YouTubeSeoExtras([], [new YouTubeChapter(0, "आरंभ"), new YouTubeChapter(45, "स्तुति"), new YouTubeChapter(100, "आरती")]);
        var with = YouTubeFreeSeoEngine.Generate("Current title: Shiv Tandav", Style, "devotional-omkr", "hi", null, null, extras);
        Assert.Contains(with.DescriptionOptions, d => d.Contains("0:45 स्तुति", StringComparison.Ordinal));
    }

    [Fact]
    public void Detected_music_is_credited_in_every_description()
    {
        var extras = new YouTubeSeoExtras([new YouTubeDetectedSong("Night Drive", "Synth Club", null, YouTubeMusicDetector.SourceDescription)], []);

        var s = YouTubeFreeSeoEngine.Generate("Current title: City timelapse", Style, "auto", "en", null, null, extras);

        Assert.Contains("Night Drive - Synth Club", s.Description);
        Assert.All(s.DescriptionOptions, d => Assert.Contains("Night Drive", d));
    }
}
